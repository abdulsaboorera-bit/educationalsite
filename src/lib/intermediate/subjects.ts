export function getSubjectBySlug(slug: string): IntermediateSubject | undefined {
  return intermediateSubjects.find((s) => s.slug === slug);
}

export function getSubjectsByClassLevel(classLevel: "11" | "12"): IntermediateSubject[] {
  return intermediateSubjects.filter((s) => s.classLevel === classLevel);
}

export function getSubjectsByGroup(groupSlug: string): IntermediateSubject[] {
  return intermediateSubjects.filter((s) => s.group.includes(groupSlug as IntermediateGroupSlug));
}

export function getCompulsorySubjects(classLevel: "11" | "12"): IntermediateSubject[] {
  return intermediateSubjects.filter((s) => s.classLevel === classLevel && s.isCompulsory);
}

export function getElectiveSubjects(groupSlug: string, classLevel: "11" | "12"): IntermediateSubject[] {
  return intermediateSubjects.filter((s) => s.group.includes(groupSlug as IntermediateGroupSlug) && s.classLevel === classLevel && !s.isCompulsory);
}

export function getAllSubjectSlugs(): string[] {
  return [...new Set(intermediateSubjects.map((s) => s.slug))];
}
